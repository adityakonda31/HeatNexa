/**
 * Translates risk reasons (e.g. "🌡 High temperature", "💧 High humidity")
 */
export function translateReason(reason, t) {
  if (!reason || typeof reason !== "string") return reason;
  const lower = reason.toLowerCase();
  if (lower.includes("temperature")) return t("highTemperature") || reason;
  if (lower.includes("humidity")) return t("highHumidity") || reason;
  if (lower.includes("solar")) return t("strongSolarExposure") || reason;
  if (lower.includes("wind")) return t("lowWindSpeed") || reason;
  if (lower.includes("age")) return t("ageVulnerability") || reason;
  if (lower.includes("outdoor")) return t("outdoorWorkExposure") || reason;
  return reason;
}

/**
 * Translates risk level (e.g. "High", "Very High", "Extreme", "Moderate", "Low")
 */
export function translateLevel(level, t) {
  if (!level || typeof level !== "string") return level;
  const key = level.toLowerCase().replace(/\s+/g, "");
  if (key === "veryhigh") return t("veryHigh") || level;
  if (key === "high") return t("high") || level;
  if (key === "extreme") return t("extreme") || level;
  if (key === "moderate") return t("moderate") || level;
  if (key === "low") return t("low") || level;
  return t(key) || level;
}

/**
 * Translates solar value (e.g. "High", "Medium", "Low")
 */
export function translateSolar(solar, t) {
  if (!solar || typeof solar !== "string") return solar;
  const s = solar.toLowerCase();
  if (s === "high") return t("solarHigh") || t("high") || solar;
  if (s === "medium" || s === "moderate") return t("solarMedium") || t("moderate") || solar;
  if (s === "low") return t("solarLow") || t("low") || solar;
  return solar;
}

